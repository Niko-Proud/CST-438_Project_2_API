-- Creates the shared schema for a new database.
-- Flyway documentation: https://documentation.red-gate.com/flyway/reference/migrations
-- Codex was used to help generate this initial migration from the project's entity model.
-- The assistance focused on matching PostgreSQL types, keys, relationships, and validation constraints.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS registry_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    product VARCHAR(200) NOT NULL CHECK (length(product) BETWEEN 1 AND 200),
    batch VARCHAR(100) CHECK (batch IS NULL OR length(batch) <= 100),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS recalled_foods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registry_item_id BIGINT,
    product VARCHAR(200) NOT NULL,
    contaminant VARCHAR(255) NOT NULL,
    recall_date DATE NOT NULL,
    manu_date DATE NOT NULL,
    batch VARCHAR(100),
    FOREIGN KEY (registry_item_id) REFERENCES registry_items(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_registry_items_user_id
    ON registry_items(user_id);

CREATE INDEX IF NOT EXISTS idx_recalled_foods_registry_item_id
    ON recalled_foods(registry_item_id);

CREATE INDEX IF NOT EXISTS idx_recalled_foods_recall_date
    ON recalled_foods(recall_date);
