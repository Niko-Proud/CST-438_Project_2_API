-- This file is a versioned Flyway migration. Spring Boot runs it against the
-- configured database during application startup.
-- Flyway migration documentation:
-- https://documentation.red-gate.com/flyway/reference/migrations
-- PostgreSQL CREATE TABLE and column-type documentation:
-- https://www.postgresql.org/docs/current/ddl-basics.html

CREATE TABLE IF NOT EXISTS users (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username TEXT NOT NULL UNIQUE,

    -- PostgreSQL BOOLEAN maps directly to the Java boolean used by User.
    -- PostgreSQL type documentation:
    -- https://www.postgresql.org/docs/current/datatype-boolean.html
    is_admin BOOLEAN NOT NULL DEFAULT FALSE

);



CREATE TABLE IF NOT EXISTS registry_items (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    product TEXT NOT NULL

        CHECK (length(product) BETWEEN 1 AND 200),

    batch TEXT

        CHECK (batch IS NULL OR length(batch) <= 100),



    FOREIGN KEY (user_id)

        REFERENCES users(id)

        ON DELETE CASCADE

);



CREATE TABLE IF NOT EXISTS recalled_foods (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    registry_item_id INTEGER,

    product TEXT NOT NULL,

    contaminant TEXT NOT NULL,

    recall_date TEXT NOT NULL,

    manu_date TEXT NOT NULL,

    batch TEXT,



    FOREIGN KEY (registry_item_id)

        REFERENCES registry_items(id)

        ON DELETE SET NULL

);



CREATE INDEX IF NOT EXISTS idx_registry_items_user_id

    ON registry_items(user_id);



CREATE INDEX IF NOT EXISTS idx_recalled_foods_registry_item_id

    ON recalled_foods(registry_item_id);



CREATE INDEX IF NOT EXISTS idx_recalled_foods_recall_date

    ON recalled_foods(recall_date);
